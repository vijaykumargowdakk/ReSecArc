import { describe, expect, it } from 'vitest';
import { loadTemplate } from '../examples/templates';
import { devicesToCsv, flowsToCsv, importDevices, parseDeviceCsv, rulesToCsv } from './csv';
import { projectToMarkdown } from './exportDoc';
import { emptyProject } from './ops';
import { laneTop } from './purdue';
import type { Project } from './schema';

function withZonesAndSites(source: Project): Project {
  return { ...emptyProject('copy'), sites: source.sites.map((s) => ({ ...s })), zones: source.zones.map((z) => ({ ...z })) };
}

describe('device CSV', () => {
  it('round-trips names, kinds, levels, zones, sites and asset details', () => {
    const source = loadTemplate('pipeline');
    const target = withZonesAndSites(source);
    const rows = parseDeviceCsv(target, devicesToCsv(source), target.sites[0].id);
    expect(rows.filter((r) => r.errors.length)).toEqual([]);
    const imported = importDevices(target, rows);
    const key = (p: Project) =>
      p.devices
        .map((d) => [d.label, d.type, d.variant, d.purdueLevel, d.zoneId, d.siteId, d.criticality, d.asset.ip].join('|'))
        .sort();
    expect(key(imported)).toEqual(key(source));
  });

  it('accepts labels and short forms, and lays devices out in their lane', () => {
    const p = withZonesAndSites(loadTemplate('water-treatment'));
    const csv = 'Name,Type,Variant,Level,Zone\nNew PLC,PLC,Compact PLC,L1,Control\nNew HMI,hmi,panel,2,\n';
    const rows = parseDeviceCsv(p, csv, p.sites[0].id);
    expect(rows.map((r) => r.errors)).toEqual([[], []]);
    const [plc, hmi] = rows.map((r) => r.device!);
    expect([plc.type, plc.variant, plc.purdueLevel, plc.zoneId]).toEqual(['plc', 'compact', 1, 'zone-control']);
    expect(plc.position.y).toBe(laneTop(1) + 37);
    expect(hmi.zoneId).toBeNull();
  });

  it('reports every problem with its line number', () => {
    const p = emptyProject();
    const csv = 'name,type,variant,level,zone,site,criticality\n,plc,,,,,\nA,toaster,,,,,\nB,plc,quantum,L9,Nowhere,Mars,extreme\n';
    const rows = parseDeviceCsv(p, csv, p.sites[0].id);
    expect(rows.map((r) => [r.line, r.errors])).toEqual([
      [2, ['name is required']],
      [3, ['unknown type "toaster"']],
      [
        4,
        [
          'unknown PLC kind "quantum"',
          'unknown level "L9"',
          'no zone named "Nowhere"; create it first',
          'no site named "Mars"',
          'criticality must be low, medium or high',
        ],
      ],
    ]);
    expect(rows.every((r) => r.device === null)).toBe(true);
  });

  it('exports flows and firewall rules with readable names', () => {
    const p = loadTemplate('water-treatment');
    expect(flowsToCsv(p).split('\n')[1]).toContain('Filtration HMI,Filtration PLC,Modbus,502');
    expect(rulesToCsv(p)).toContain('IT/OT firewall,1,allow,zone: Enterprise,Remote access jump host,https,443');
  });
});

describe('architecture document', () => {
  it('describes zones, conduits, devices, flows and rules for every site', () => {
    const md = projectToMarkdown(loadTemplate('pipeline'), new Date('2026-10-25T00:00:00Z'));
    expect(md).toContain('# Westridge Gas Pipeline (fictional demo)');
    expect(md).toContain('generated by ConduitOT on 2026-10-25');
    expect(md).toContain('## Site: Compressor station 1');
    expect(md).toContain('### Firewall rules: Station firewall');
    expect(md).toContain('| Station controller | PAC | L1 | Station control |');
    expect(md).toContain('Default action when no rule matches: **deny**.');
    expect(md).not.toMatch(/\| undefined/);
  });
});

describe('CSV safety', () => {
  it('escapes spreadsheet formulas on export and restores them on import', () => {
    const p = loadTemplate('water-treatment');
    const evil = { ...p, devices: p.devices.map((d, i) => (i === 0 ? { ...d, label: '=HYPERLINK("http://x","y")' } : d)) };
    const csv = devicesToCsv(evil);
    expect(csv).toContain(`"'=HYPERLINK(""http://x"",""y"")"`);
    expect(csv).not.toMatch(/(^|,)=HYPERLINK/m);
    const target = withZonesAndSites(evil);
    const rows = parseDeviceCsv(target, csv, target.sites[0].id);
    expect(rows[0].device?.label).toBe('=HYPERLINK("http://x","y")');
  });
});
