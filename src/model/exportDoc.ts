// Markdown architecture document: a readable record of what the project contains.
import { kindLabel } from './catalog';
import { checkById, runChecks } from './checks';
import { deriveConduits } from './conduits';
import { endpointName } from './csv';
import { describePolicy } from './policies';
import { flowLabel, getProtocol } from './protocols';
import { levelLabel } from './purdue';
import type { Project } from './schema';

const cell = (s: string | number) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ') || '—';
const table = (head: string[], rows: (string | number)[][]) =>
  rows.length === 0
    ? '_None._\n'
    : [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n') + '\n';

export function projectToMarkdown(project: Project, generatedAt = new Date()): string {
  const zone = new Map(project.zones.map((z) => [z.id, z.name]));
  const area = new Map(project.areas.map((a) => [a.id, a.name]));
  const device = new Map(project.devices.map((d) => [d.id, d]));
  const out: string[] = [];

  out.push(`# ${project.name}\n`);
  out.push(`Architecture record generated by ConduitOT on ${generatedAt.toISOString().slice(0, 10)}.\n`);
  out.push(
    `${project.sites.length} site(s) · ${project.devices.length} devices · ${project.links.length} links · ${project.flows.length} protocol flows · ${project.zones.length} zones\n`,
  );

  out.push('## Security zones\n');
  out.push(
    table(
      ['Zone', 'Trusted', 'Target SL', 'Devices'],
      project.zones.map((z) => [z.name, z.trusted ? 'yes' : 'no', z.targetSL, project.devices.filter((d) => d.zoneId === z.id).length]),
    ),
  );

  if (project.networks.length) {
    const site = new Map(project.sites.map((s) => [s.id, s.name]));
    out.push('## Networks\n');
    out.push(
      table(
        ['Network', 'Subnet', 'VLAN', 'Zone', 'Site'],
        project.networks.map((n) => [
          n.name,
          n.cidr,
          n.vlan ?? '',
          n.zoneId ? (zone.get(n.zoneId) ?? '') : '',
          n.siteId ? (site.get(n.siteId) ?? '') : 'all sites',
        ]),
      ),
    );
  }

  out.push('## Conduits\n');
  out.push(
    table(
      ['Between', 'Links', 'Flows'],
      deriveConduits(project).map((c) => [`${zone.get(c.zones[0])} ↔ ${zone.get(c.zones[1])}`, c.linkIds.length, c.flowIds.length]),
    ),
  );

  out.push('## Security findings\n');
  out.push('Design-time checks based on IEC 62443 zone and conduit principles, plus company policy rules. Not a compliance assessment.\n');
  const findings = runChecks(project);
  out.push(table(['Severity', 'Finding', 'Detail', 'Reference', 'Suggested fix'], findings.map((f) => [f.severity, f.headline, f.message, f.reference ?? '', f.fix])));
  if (project.disabledChecks.length) {
    out.push(`Checks switched off for this project: ${project.disabledChecks.map((id) => checkById(id)?.title ?? id).join(', ')}.\n`);
  }
  if (project.policies.length) {
    out.push('### Company policies\n');
    out.push(table(['Rule', 'Forbids', 'Severity', 'Enabled'], project.policies.map((r) => [r.name, describePolicy(r, project), r.severity, r.enabled ? 'yes' : 'no'])));
  }

  for (const site of project.sites) {
    const devices = project.devices.filter((d) => d.siteId === site.id).sort((a, b) => b.purdueLevel - a.purdueLevel || a.label.localeCompare(b.label));
    out.push(`## Site: ${site.name}\n`);
    const areas = project.areas.filter((a) => a.siteId === site.id);
    if (areas.length) out.push(`Areas: ${areas.map((a) => a.name).join(', ')}\n`);
    out.push('### Devices\n');
    out.push(
      table(
        ['Name', 'Kind', 'Level', 'Zone', 'Area', 'IP', 'Vendor', 'Model', 'Firmware', 'Criticality', 'Tags'],
        devices.map((d) => [
          d.label,
          kindLabel(d.type, d.variant),
          levelLabel(d.purdueLevel),
          d.zoneId ? (zone.get(d.zoneId) ?? '') : '',
          d.areaId ? (area.get(d.areaId) ?? '') : '',
          d.asset.ip,
          d.asset.vendor,
          d.asset.model,
          d.asset.firmware,
          d.criticality,
          d.tags.join(', '),
        ]),
      ),
    );
    if (project.fieldDefs.length) {
      out.push('### Custom fields\n');
      out.push(table(['Device', ...project.fieldDefs.map((f) => f.label)], devices.map((d) => [d.label, ...project.fieldDefs.map((f) => d.fields[f.id] ?? '')])));
    }
    const ids = new Set(devices.map((d) => d.id));
    out.push('### Protocol flows\n');
    out.push(
      table(
        ['From', 'To', 'Protocol', 'Port', 'Settings'],
        project.flows
          .filter((f) => ids.has(f.source))
          .map((f) => [
            device.get(f.source)?.label ?? f.source,
            device.get(f.target)?.label ?? f.target,
            getProtocol(f.protocol)?.label ?? f.protocol,
            f.port ?? 'n/a',
            flowLabel(f.protocol, f.settings),
          ]),
      ),
    );
    for (const fw of devices.filter((d) => d.firewall)) {
      out.push(`### Firewall rules: ${fw.label}\n`);
      out.push(
        table(
          ['#', 'Action', 'Source', 'Destination', 'Protocol', 'Port', 'Note'],
          fw.firewall!.rules.map((r, i) => [i + 1, r.action, endpointName(project, r.src), endpointName(project, r.dst), r.protocol, r.port ?? 'any', r.note]),
        ),
      );
      out.push(`Default action when no rule matches: **${fw.firewall!.defaultAction}**.\n`);
    }
    const notes = project.notes.filter((n) => n.siteId === site.id && n.text.trim());
    if (notes.length) {
      out.push('### Notes\n');
      out.push(notes.map((n) => `- ${n.text.trim().replace(/\s*\n\s*/g, ' ')}`).join('\n') + '\n');
    }
  }
  return out.join('\n');
}
