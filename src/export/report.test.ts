import { describe, expect, it } from 'vitest';
import { loadTemplate, TEMPLATES } from '../examples/templates';
import { findAttackPaths } from '../model/attack/paths';
import { runChecks } from '../model/checks';
import { addLink } from '../model/ops';
import { projectToHtmlReport } from './report';

const at = new Date('2026-10-29T09:00:00Z');

describe('projectToHtmlReport', () => {
  it('includes every site with its diagram, for every template', () => {
    for (const t of TEMPLATES) {
      const p = loadTemplate(t.id);
      const html = projectToHtmlReport(p, at);
      p.sites.forEach((s, i) => {
        expect(html, `${t.id}: ${s.name}`).toContain(`<h2 id="site-${i + 1}-h">Site: ${s.name}</h2>`);
        expect(html).toContain(`aria-labelledby="s${i + 1}-title"`);
      });
      expect(html.match(/<figure><svg /g)).toHaveLength(p.sites.length);
      for (const d of p.devices) expect(html, d.label).toContain(`<td>${d.label.replace(/&/g, '&amp;')}</td>`);
    }
  });

  it('lists security findings and the attack path from the office to the RTU', () => {
    const demo = loadTemplate('water-treatment');
    const office = demo.devices.find((d) => d.label === 'Office workstation')!;
    const rtu = demo.devices.find((d) => d.label === 'Pump station RTU')!;
    const p = addLink(demo, office.id, rtu.id);
    const html = projectToHtmlReport(p, at);
    expect(runChecks(p).length).toBeGreaterThan(0);
    expect(html).toContain('IEC 62443 communication violation');
    expect(findAttackPaths(p).paths.some((x) => x.entryId === office.id && x.targetId === rtu.id)).toBe(true);
    expect(html).toContain('Office workstation → Pump station RTU</h3>');
    expect(html).toMatch(/<a href="https:\/\/attack\.mitre\.org\/techniques\/T\d+/);
    expect(html).toContain('Not a compliance assessment.');
  });

  it('cannot be made to run a script by a crafted project', () => {
    const p = loadTemplate('water-treatment');
    p.name = '</title><script>alert(1)</script>';
    p.devices[0] = { ...p.devices[0], label: '<img src=x onerror=alert(1)>' };
    p.notes[0] = { ...p.notes[0], text: '<script>alert(2)</script>\nsecond line' };
    p.zones[0] = { ...p.zones[0], name: '"><svg onload=alert(3)>' };
    const html = projectToHtmlReport(p, at);
    expect(html).not.toMatch(/<script|<img|<svg onload/i);
    expect(html).toContain(`<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:">`);
    expect(html).toContain('&lt;script&gt;alert(2)&lt;/script&gt;<br>second line');
  });

  it('dates the report and lists revisions when there are any', () => {
    const p = loadTemplate('water-treatment');
    expect(projectToHtmlReport(p, at)).toContain('generated by ConduitOT on 2026-10-29');
    expect(projectToHtmlReport(p, at)).not.toContain('id="revisions"');
    p.revisions = [{ id: 'r1', name: 'Baseline', createdAt: '2026-10-01T08:30:00.000Z', design: p }];
    expect(projectToHtmlReport(p, at)).toContain('<td>Baseline</td><td>2026-10-01 08:30</td>');
  });
});
