// Generates src/model/attack/icsTechniques.ts from MITRE ATT&CK for ICS, so no technique ID,
// name or tactic is ever typed by hand. Downloads the dataset at a pinned release tag of mitre/cti
// and fails if a technique we use is missing, revoked or deprecated, or is not under the tactic we
// put it in. Run with `node scripts/attack-ics.mjs` after changing TAG or TECHNIQUES.
import { mkdirSync, writeFileSync } from 'node:fs';

const TAG = 'ATT&CK-v20.0';
const URL = `https://raw.githubusercontent.com/mitre/cti/${encodeURIComponent(TAG)}/ics-attack/ics-attack.json`;
const OUT = 'src/model/attack/icsTechniques.ts';

/** Techniques the attack path labels use, each with the tactic (shortname) it is shown under. */
const TECHNIQUES = {
  T0883: 'initial-access', // Internet Accessible Device
  T0822: 'initial-access', // External Remote Services
  T0865: 'initial-access', // Spearphishing Attachment
  T0860: 'initial-access', // Wireless Compromise
  T0866: ['initial-access', 'lateral-movement'], // Exploitation of Remote Services
  T0886: 'lateral-movement', // Remote Services
  T0843: 'lateral-movement', // Program Download
  'T1692.001': 'impair-process-control', // Command Message (replaced T0855 in v19)
  T0880: 'impact', // Loss of Safety
  T0831: 'impact', // Manipulation of Control
};

const res = await fetch(URL);
if (!res.ok) throw new Error(`Download failed: ${res.status} ${URL}`);
const bundle = await res.json();
const objects = bundle.objects;
const attackRef = (o) => o.external_references?.find((r) => r.source_name === 'mitre-attack');
const q = (s) => `'${s.replace(/[\\']/g, '\\$&')}'`;
const usable = (o) => !o.revoked && !o.x_mitre_deprecated;

const tactics = objects
  .filter((o) => o.type === 'x-mitre-tactic' && usable(o))
  .map((o) => ({ shortname: o.x_mitre_shortname, id: attackRef(o).external_id, name: o.name, url: attackRef(o).url }));
const matrix = objects.find((o) => o.type === 'x-mitre-matrix');
// Tactics in the matrix's own order, which follows the attack lifecycle.
const order = new Map(matrix.tactic_refs.map((ref, i) => [objects.find((o) => o.id === ref)?.x_mitre_shortname, i]));
tactics.sort((a, b) => order.get(a.shortname) - order.get(b.shortname));

const errors = [];
const techniques = [];
for (const [id, wanted] of Object.entries(TECHNIQUES)) {
  const found = objects.filter((o) => o.type === 'attack-pattern' && attackRef(o)?.external_id === id);
  const live = found.filter(usable);
  if (live.length !== 1) {
    errors.push(`${id}: ${found.length ? 'revoked or deprecated' : 'missing'} in ${TAG}`);
    continue;
  }
  const t = live[0];
  const phases = t.kill_chain_phases.filter((k) => k.kill_chain_name === 'mitre-ics-attack').map((k) => k.phase_name);
  for (const tactic of [wanted].flat()) {
    if (!phases.includes(tactic)) errors.push(`${id} ${t.name}: not under ${tactic} (has ${phases.join(', ')})`);
  }
  techniques.push({ id, name: t.name, tactics: phases, url: attackRef(t).url });
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const tacticType = tactics.map((t) => `'${t.shortname}'`).join(' | ');
const lines = [
  `// Generated by scripts/attack-ics.mjs from MITRE ATT&CK® for ICS, ${TAG} (github.com/mitre/cti).`,
  '// Do not edit by hand: change the script and run it again.',
  '',
  `export const ATTACK_ICS_RELEASE = ${q(TAG)};`,
  '',
  `export type IcsTacticName = ${tacticType};`,
  '',
  'export interface IcsTactic {',
  '  id: string;',
  '  name: string;',
  '  url: string;',
  '}',
  '',
  'export interface IcsTechnique {',
  '  id: string;',
  '  name: string;',
  '  tactics: readonly IcsTacticName[];',
  '  url: string;',
  '}',
  '',
  '/** Every ATT&CK for ICS tactic, in the matrix order. */',
  'export const ICS_TACTICS: Record<IcsTacticName, IcsTactic> = {',
  ...tactics.map((t) => `  '${t.shortname}': { id: '${t.id}', name: ${q(t.name)}, url: '${t.url}' },`),
  '};',
  '',
  '/** The techniques attack paths are labelled with. */',
  'export const ICS_TECHNIQUES = {',
  ...techniques.map(
    (t) => `  '${t.id}': { id: '${t.id}', name: ${q(t.name)}, tactics: [${t.tactics.map((x) => `'${x}'`).join(', ')}], url: '${t.url}' },`,
  ),
  '} as const satisfies Record<string, IcsTechnique>;',
  '',
  'export type IcsTechniqueId = keyof typeof ICS_TECHNIQUES;',
  '',
];
mkdirSync('src/model/attack', { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`attack-ics: wrote ${techniques.length} techniques and ${tactics.length} tactics from ${TAG} to ${OUT}`);
