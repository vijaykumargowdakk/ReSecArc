#!/usr/bin/env python3
"""Generate FILEMAP.md: a markdown tree of every file with sizes and mtimes.

Usage:
    python filemap_watcher.py --once   regenerate once and exit
    python filemap_watcher.py          watch for changes (needs `watchdog`)
"""
import io
import os
import sys
import time
from datetime import datetime

if sys.platform == "win32":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.abspath(__file__))
OUTPUT_NAME = "FILEMAP.md"
OUTPUT = os.path.join(ROOT, OUTPUT_NAME)
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv", ".idea",
             ".vscode", ".mypy_cache", ".pytest_cache"}
SKIP_EXTS = {".pyc", ".pyo", ".pyd"}
DEBOUNCE_SECONDS = 1.5


def human_size(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n} B" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def mtime(path):
    return datetime.fromtimestamp(os.path.getmtime(path)).strftime("%Y-%m-%d %H:%M")


def build_tree(directory, depth, lines, counts):
    try:
        entries = sorted(os.scandir(directory), key=lambda e: (not e.is_dir(), e.name.lower()))
    except OSError:
        return
    indent = "  " * depth
    for entry in entries:
        if entry.is_dir(follow_symlinks=False):
            if entry.name in SKIP_DIRS:
                continue
            counts[0] += 1
            lines.append(f"{indent}- 📁 **{entry.name}/**")
            build_tree(entry.path, depth + 1, lines, counts)
        else:
            if os.path.splitext(entry.name)[1].lower() in SKIP_EXTS:
                continue
            if depth == 0 and entry.name == OUTPUT_NAME:
                continue
            try:
                size = human_size(entry.stat().st_size)
                modified = mtime(entry.path)
            except OSError:
                continue
            counts[1] += 1
            lines.append(f"{indent}- 📄 {entry.name} — {size}, {modified}")


def generate():
    lines, counts = [], [0, 0]
    build_tree(ROOT, 0, lines, counts)
    header = [
        "# FILEMAP",
        "",
        f"*Auto-generated by filemap_watcher.py at {datetime.now():%Y-%m-%d %H:%M:%S}. Do not edit by hand.*",
        "",
        f"**{counts[0]} directories, {counts[1]} files**",
        "",
    ]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header + lines) + "\n")
    print(f"Wrote {OUTPUT_NAME}: {counts[0]} directories, {counts[1]} files")


def watch():
    try:
        from watchdog.events import FileSystemEventHandler
        from watchdog.observers import Observer
    except ImportError:
        print("watchdog is not installed (pip install watchdog); use --once instead.")
        sys.exit(1)

    state = {"dirty": False, "last": 0.0}

    class Handler(FileSystemEventHandler):
        def on_any_event(self, event):
            path = os.path.abspath(event.src_path)
            if path == OUTPUT:
                return
            rel_parts = os.path.relpath(path, ROOT).split(os.sep)
            if any(p in SKIP_DIRS for p in rel_parts):
                return
            state["dirty"] = True
            state["last"] = time.time()

    generate()
    observer = Observer()
    observer.schedule(Handler(), ROOT, recursive=True)
    observer.start()
    try:
        while True:
            time.sleep(0.5)
            if state["dirty"] and time.time() - state["last"] >= DEBOUNCE_SECONDS:
                state["dirty"] = False
                generate()
    except KeyboardInterrupt:
        observer.stop()
    observer.join()


if __name__ == "__main__":
    if "--once" in sys.argv:
        generate()
    else:
        watch()
